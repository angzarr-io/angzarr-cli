//! End to end: a blackjack application the CLI scaffolds, run. `scaffold
//! app` writes its startup from the spec's protos (the host config listing
//! every component, the table and its two policies in process and the
//! player a Python child, the store in memory; the manifest; the build
//! script; the async `main` running the generated `register()` with the
//! config), `scaffold rust` the Rust table and its two policies, `scaffold
//! python` the player at `player/`. The domain layer is examples-proto's
//! (`--domain-crate examples_proto`), which agg-table and
//! table-player-policies are written over, so nothing is converted: the
//! table's interface is that domain layer's generated `TableAggregate`, and
//! the user's files (`tests/e2e/blackjack`) are its implementation,
//! agg-table's `Table`, the policies' implementations over
//! table-player-policies, a basic-strategy player, a
//! driver playing seed 21's hand, and the table's crates added to the
//! manifest. From the deal the turn crosses to the Python child and back
//! by the policies alone, until the round settles. The hand is agg-table's
//! `test_support::seed_21`, the one every driver of the table plays: the
//! driver checks the players' moves, the table's events and the settlement
//! against it, and prints the settlement this test asserts.
//!
//! agg-table, examples-proto and table-player-policies are examples-rust's,
//! at [`EXAMPLES_RUST_REV`]: git dependencies pinned by hash, as
//! angzarr-embedded and angzarr-client are, so the outcome is that commit's
//! and not whatever a local checkout holds. The app has one angzarr-embedded
//! and one generator: the manifest patches examples-rust's angzarr-embedded
//! to the CLI's (a checkout at [`ANGZARR_EMBEDDED_REV`]) and its
//! angzarr-build to this workspace's, so examples-proto's domain layer and
//! the app's adapters are generated by the same code.
//!
//! Ignored: it needs the network (buf.build, GitHub) and uv.

mod common;

use angzarr_codegen::{ANGZARR_EMBEDDED_GIT, ANGZARR_EMBEDDED_REV};
use common::{angzarr, copy_dir, here, overlay};

#[path = "../../../test-support/test_dir.rs"]
mod test_dir;
use test_dir::TestDir;

const PROTOS: &[&str] = &[
    "io/angzarr/examples/v1/table.proto",
    "io/angzarr/examples/v1/player.proto",
    "io/angzarr/examples/v1/policies.proto",
];

/// The examples-rust commit the table's crates are built from: its main,
/// where agg-table implements the table's generated interface over
/// examples-proto's generated domain layer, and has seed 21's hand as test
/// support.
const EXAMPLES_RUST_REV: &str = "73621e6f8a202321b7e21e9672dad926df22c665";
/// Where [`EXAMPLES_RUST_REV`] is fetched from.
const EXAMPLES_RUST_GIT: &str = "https://github.com/angzarr-io/angzarr-examples-rust";

#[test]
#[ignore = "needs the network (buf.build, GitHub) and uv"]
fn a_scaffolded_blackjack_app_plays_seed_21_to_settlement_with_the_python_player() {
    let app = TestDir::new(concat!(env!("CARGO_PKG_NAME"), "-blackjack"));
    copy_dir(
        &here().join("../../angzarr-project/proto/io/angzarr"),
        &app.join("proto/io/angzarr"),
    );
    let build = here().join("../angzarr-build").display().to_string();
    scaffold(&app, &build);
    // The user's part: the logic, the driver (over the scaffold's stub),
    // and the table's crates, added to the scaffolded manifest (a
    // workspace of its own, wherever the temporary directory is), with
    // examples-rust's angzarr-embedded and angzarr-build patched to the
    // app's.
    overlay(&here().join("tests/e2e/blackjack"), &app);
    let _embedded = patch_manifest(&app, &build);

    let out = common::run(&app);
    assert!(
        out.status.success(),
        "the app runs:\n{}",
        String::from_utf8_lossy(&out.stderr)
    );
    assert_eq!(
        String::from_utf8(out.stdout).unwrap(),
        [
            "seat 0: wager 40 returned 80 stack 540",
            "seat 1: wager 20 returned 40 stack 520",
            "house -60",
            "",
        ]
        .join("\n")
    );
}

/// The app scaffolded in `app`: its startup, the Rust table and its two
/// policies, and the Python player, the startup building with angzarr-build
/// at `build`.
fn scaffold(app: &std::path::Path, build: &str) {
    let mut startup = vec![
        "scaffold",
        "app",
        "-I",
        "proto",
        "--src",
        ".",
        "--name",
        "blackjack",
        "--language",
        "player=python",
        "--in-memory",
        "--angzarr-build-path",
        build,
        "--domain-crate",
        "examples_proto",
        "--domain-wire",
        "examples_proto::v1",
    ];
    startup.extend(PROTOS);
    angzarr(app, &startup);
    angzarr(
        app,
        &[
            "scaffold", "rust", "-I", "proto", "--src", "src", PROTOS[0], PROTOS[2],
        ],
    );
    angzarr(
        app,
        &[
            "scaffold",
            "python",
            "-I",
            "proto",
            "--src",
            "player",
            "--domain",
            "player",
            "--proto-git",
            "https://github.com/angzarr-io/angzarr-project",
            "--proto-ref",
            "40c2fad6c5d01f4cb223deb7faf8f776b42f9057",
            PROTOS[1],
        ],
    );
}

/// The table's crates added to the app's manifest (agg-table with its test
/// support, seed 21's hand), examples-rust's angzarr-embedded patched to a
/// checkout of the CLI's (returned, removed when it drops), and its
/// angzarr-build to this workspace's (`build`).
fn patch_manifest(app: &std::path::Path, build: &str) -> TestDir {
    // Beside the app, not in it: a path dependency under the app's
    // directory would be a member of its workspace.
    let embedded = TestDir::new(concat!(env!("CARGO_PKG_NAME"), "-blackjack-embedded"));
    let into = embedded.display().to_string();
    git(app, &["clone", "--quiet", ANGZARR_EMBEDDED_GIT, &into]);
    git(&embedded, &["checkout", "--quiet", ANGZARR_EMBEDDED_REV]);
    let examples = format!("{{ git = \"{EXAMPLES_RUST_GIT}\", rev = \"{EXAMPLES_RUST_REV}\" }}");
    // Seed 21's hand, which the driver plays, is agg-table's test support.
    let agg_table = format!(
        "{{ git = \"{EXAMPLES_RUST_GIT}\", rev = \"{EXAMPLES_RUST_REV}\", features = [\"test-support\"] }}"
    );
    let patched: String = [
        "angzarr-embedded",
        "angzarr-embedded-host",
        "angzarr-embedded-macros",
    ]
    .iter()
    .map(|c| {
        let path = embedded.join("crates").join(c).display().to_string();
        format!("{c} = {{ path = {path:?} }}\n")
    })
    .collect();
    let manifest = std::fs::read_to_string(app.join("Cargo.toml")).unwrap();
    let manifest = manifest.replace(
        "\n[build-dependencies]",
        &format!(
            "agg-table = {agg_table}\nexamples-proto = {examples}\n\
             table-player-policies = {examples}\n\n[build-dependencies]"
        ),
    ) + &format!(
        "\n[patch.\"{ANGZARR_EMBEDDED_GIT}\"]\n{patched}\n\
         [patch.\"https://github.com/angzarr-io/angzarr-cli\"]\n\
         angzarr-build = {{ path = {build:?} }}\n\n[workspace]\n"
    );
    std::fs::write(app.join("Cargo.toml"), manifest).unwrap();
    embedded
}

/// `git <args>` in `dir`, which must succeed.
fn git(dir: &std::path::Path, args: &[&str]) {
    let out = std::process::Command::new("git")
        .args(args)
        .current_dir(dir)
        .output()
        .expect("git runs");
    assert!(
        out.status.success(),
        "git {args:?}:\n{}",
        String::from_utf8_lossy(&out.stderr)
    );
}

