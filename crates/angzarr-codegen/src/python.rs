//! The Python scaffold: one domain's uv project, served to angzarr-embedded
//! as a child process through angzarr-client-python's harness
//! (`angzarr_client.child`).
//!
//! The project is split so that the user's logic never names the harness:
//!
//! - written once, the user's ([`Owner::User`]): `pyproject.toml`, the
//!   package's `__init__.py`, `tests/__init__.py`, and per component its
//!   interface (a `typing.Protocol` over the domain's messages) and its
//!   implementation (every method `raise NotImplementedError  # TODO`);
//! - rewritten on every run, the CLI's ([`Owner::Generated`]): `buf.gen.yaml`
//!   (the message types), `main.py`, `__main__.py`, `_version.py`, the
//!   `_gen` packages' `__init__.py`, and per component its dispatch, which
//!   adapts the router binding's wire calls to calls on the interface.
//!
//! A change to the harness or to the scaffold touches only generated files.

use std::collections::BTreeSet;

use prost_reflect::{Kind, MessageDescriptor};

use crate::error::CodegenError;
use crate::model::{self, Component, ComponentKind, MARKUP_KINDS};
use crate::rust::snake;
use crate::scaffold::{Owner, ScaffoldFile};

/// The angzarr Python package (angzarr-client-python) the scaffold depends
/// on, pinned by commit: every project this CLI scaffolds gets this one.
pub const CLIENT_PYTHON_REV: &str = "49a0c219035aefb54d75bf26185507e88a5fc745";
/// Where [`CLIENT_PYTHON_REV`] is fetched from.
pub const CLIENT_PYTHON_GIT: &str = "https://github.com/angzarr-io/angzarr-client-python";

/// The proto packages angzarr-client-python ships generated, imported from
/// `angzarr_client.proto` and never generated into a project.
const FRAMEWORK_PACKAGES: &[&str] = &["io.angzarr.v1", "io.angzarr.status", "sererr.v1"];
/// Black's line width, which the generated Python is laid out to.
const WIDTH: usize = 88;
/// The header of every generated file.
const GENERATED: &str =
    "# @generated by angzarr-codegen. Do not edit: `angzarr scaffold python` rewrites it.\n";

/// Where `buf generate` reads the domain's protos from.
#[derive(Clone, PartialEq, Eq, Debug)]
pub enum ProtoInput {
    /// A git repository at a revision, the protos under `subdir`.
    Git {
        url: String,
        rev: String,
        subdir: String,
    },
    /// A directory, relative to the project root.
    Directory(String),
}

/// One Python domain's project.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct PythonApp {
    /// The domain served, e.g. `player`: the package is `angzarr_<domain>`,
    /// the distribution and its script `angzarr-<domain>`.
    pub domain: String,
    pub protos: ProtoInput,
    /// The build version the domain reports as its rules_version.
    pub rules_version: String,
}

impl PythonApp {
    fn package(&self) -> String {
        format!("angzarr_{}", self.domain.replace('-', "_"))
    }

    fn script(&self) -> String {
        format!("angzarr-{}", self.domain.replace('_', "-"))
    }
}

/// The project of `app.domain`: every component of that domain declared in
/// `files`, as the files listed in the module doc. Paths are relative to
/// the project root.
pub fn scaffold_python(
    descriptor_set: &[u8],
    files: &[&str],
    app: &PythonApp,
) -> Result<Vec<ScaffoldFile>, CodegenError> {
    let components: Vec<Component> = model::components(descriptor_set, files, MARKUP_KINDS)?
        .into_iter()
        .filter(|c| c.domain == app.domain && c.kind != ComponentKind::Policy)
        .collect();
    if components.is_empty() {
        return Err(CodegenError::PythonNoDomain {
            domain: app.domain.clone(),
        });
    }
    for component in &components {
        check(component)?;
    }
    let package = app.package();
    let src = format!("src/{package}");
    let anchor = components[0].anchor.full_name().to_string();
    let file = |path: String, source: String, owner: Owner| ScaffoldFile {
        component: anchor.clone(),
        path,
        source,
        owner,
    };

    let mut out = vec![
        file(
            "pyproject.toml".to_string(),
            pyproject(app, &components),
            Owner::User,
        ),
        file(
            "buf.gen.yaml".to_string(),
            buf_gen(app, &components),
            Owner::Generated,
        ),
        file(format!("{src}/__init__.py"), String::new(), Owner::User),
        file(
            format!("{src}/__main__.py"),
            format!("{GENERATED}\nfrom {package}.main import main\n\nmain()\n"),
            Owner::Generated,
        ),
        file(
            format!("{src}/_version.py"),
            format!(
                "{GENERATED}\"\"\"The build version the {} domain reports as its rules_version.\"\"\"\n\n__version__ = {:?}\n",
                app.domain, app.rules_version
            ),
            Owner::Generated,
        ),
        file(
            format!("{src}/main.py"),
            main_py(app, &components),
            Owner::Generated,
        ),
        file("tests/__init__.py".to_string(), String::new(), Owner::User),
    ];
    let mut packages = BTreeSet::new();
    for component in &components {
        let dir = module_dir(&component.anchor);
        let mut path = String::new();
        for part in std::iter::once("_gen").chain(dir.split('/')) {
            if !path.is_empty() {
                path.push('/');
            }
            path.push_str(part);
            packages.insert(path.clone());
        }
        let stem = snake(&component.name);
        out.push(ScaffoldFile {
            component: component.anchor.full_name().to_string(),
            path: format!("{src}/{stem}.py"),
            source: interface(app, component),
            owner: Owner::User,
        });
        out.push(ScaffoldFile {
            component: component.anchor.full_name().to_string(),
            path: format!("{src}/{stem}_impl.py"),
            source: implementation(app, component),
            owner: Owner::User,
        });
        out.push(ScaffoldFile {
            component: component.anchor.full_name().to_string(),
            path: format!("{src}/_gen/{dir}/{stem}_angzarr.py"),
            source: dispatch(app, component),
            owner: Owner::Generated,
        });
    }
    for dir in packages {
        out.push(file(
            format!("{src}/{dir}/__init__.py"),
            GENERATED.to_string(),
            Owner::Generated,
        ));
    }
    out.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(out)
}

/// What the Python scaffold emits: an aggregate's commands and events.
fn check(component: &Component) -> Result<(), CodegenError> {
    if component.kind != ComponentKind::Aggregate {
        return Err(CodegenError::PythonKind {
            component: component.anchor.full_name().to_string(),
        });
    }
    for input in &component.inputs {
        if input.fact {
            return Err(CodegenError::PythonFact {
                message: input.message.full_name().to_string(),
            });
        }
        if !input.refuses.is_empty() {
            return Err(CodegenError::PythonRefuses {
                message: input.message.full_name().to_string(),
            });
        }
    }
    Ok(())
}

/// `io/angzarr/examples/v1` for a message of `io/angzarr/examples/v1/x.proto`.
fn module_dir(message: &MessageDescriptor) -> String {
    let name = message.parent_file().name().to_string();
    name.rsplit_once('/')
        .map_or(String::new(), |(dir, _)| dir.to_string())
}

/// The dotted module of a message's pb2, under the project's `_gen`.
fn pb2_module(app: &PythonApp, message: &MessageDescriptor) -> String {
    let name = message.parent_file().name().to_string();
    let stem = name.trim_end_matches(".proto").replace('/', ".");
    format!("{}._gen.{stem}_pb2", app.package())
}

/// The pb2 alias the dispatch imports a message's module as: `_<stem>`.
fn alias(message: &MessageDescriptor) -> String {
    let name = message.parent_file().name().to_string();
    let stem = name
        .rsplit('/')
        .next()
        .unwrap_or(&name)
        .trim_end_matches(".proto");
    format!("_{stem}")
}

/// One method of a component's interface.
struct Method {
    name: String,
    /// `(param, type)`, after `self`.
    params: Vec<(String, String)>,
    returns: String,
    todo: String,
}

fn methods(component: &Component) -> Vec<Method> {
    let state = component.anchor.name().to_string();
    let mut out = Vec::new();
    for input in &component.inputs {
        let ty = input.message.name().to_string();
        let returns = match input.emits.as_slice() {
            [] => "None".to_string(),
            [one] => one.name().to_string(),
            several => format!(
                "list[{}]",
                several
                    .iter()
                    .map(|e| e.name())
                    .collect::<Vec<_>>()
                    .join(" | ")
            ),
        };
        out.push(Method {
            name: snake(&ty),
            params: vec![
                ("cmd".to_string(), ty.clone()),
                ("state".to_string(), state.clone()),
            ],
            returns,
            todo: format!("decide {ty}"),
        });
    }
    for event in &component.events {
        let ty = event.name().to_string();
        out.push(Method {
            name: format!("apply_{}", snake(&ty)),
            params: vec![
                ("event".to_string(), ty.clone()),
                ("state".to_string(), state.clone()),
            ],
            returns: "None".to_string(),
            todo: format!("fold {ty} into the state"),
        });
    }
    out
}

/// Every message the interface names, by pb2 module.
fn interface_imports(app: &PythonApp, component: &Component) -> String {
    let mut by_module: std::collections::BTreeMap<String, BTreeSet<String>> = Default::default();
    let mut add = |m: &MessageDescriptor| {
        by_module
            .entry(pb2_module(app, m))
            .or_default()
            .insert(m.name().to_string());
    };
    add(&component.anchor);
    for input in &component.inputs {
        add(&input.message);
        input.emits.iter().for_each(&mut add);
    }
    component.events.iter().for_each(&mut add);
    let mut out = String::new();
    for (module, names) in by_module {
        out.push_str(&format!("from {module} import (\n"));
        for name in names {
            out.push_str(&format!("    {name},\n"));
        }
        out.push_str(")\n");
    }
    out
}

/// `def name(self, a: A, b: B) -> R:` laid out as black lays it out at
/// `indent`, followed by `tail` (` ...` or nothing).
fn signature(indent: usize, method: &Method, tail: &str) -> String {
    let pad = " ".repeat(indent);
    let params: Vec<String> = std::iter::once("self".to_string())
        .chain(method.params.iter().map(|(p, t)| format!("{p}: {t}")))
        .collect();
    let line = format!(
        "{pad}def {}({}) -> {}:{tail}",
        method.name,
        params.join(", "),
        method.returns
    );
    if line.len() <= WIDTH {
        return line;
    }
    let inner = format!("{pad}    {}", params.join(", "));
    if inner.len() <= WIDTH {
        return format!(
            "{pad}def {}(\n{inner}\n{pad}) -> {}:{tail}",
            method.name, method.returns
        );
    }
    let exploded: String = params.iter().map(|p| format!("{pad}    {p},\n")).collect();
    format!(
        "{pad}def {}(\n{exploded}{pad}) -> {}:{tail}",
        method.name, method.returns
    )
}

fn interface(app: &PythonApp, component: &Component) -> String {
    let name = &component.name;
    let stem = snake(name);
    let mut out = format!(
        "\"\"\"{name}: the interface of ``{}``,\n\
         written once by ``angzarr scaffold python`` and yours from then on:\n\
         ``--missing`` adds the methods it lacks. It names only the domain's messages;\n\
         the generated dispatch (``_gen/.../{stem}_angzarr.py``) calls it.\n\"\"\"\n\n\
         from __future__ import annotations\n\nfrom typing import Protocol\n\n",
        component.anchor.full_name()
    );
    out.push_str(&interface_imports(app, component));
    out.push_str(&format!("\n\nclass {name}(Protocol):\n"));
    let body: Vec<String> = methods(component)
        .iter()
        .map(|m| format!("{}\n", signature(4, m, " ...")))
        .collect();
    out.push_str(&body.join("\n"));
    out
}

fn implementation(app: &PythonApp, component: &Component) -> String {
    let name = &component.name;
    let mut out = format!(
        "\"\"\"{name}Impl: the implementation of ``{name}``, written\n\
         once by ``angzarr scaffold python`` and yours from then on: ``--missing``\n\
         adds the methods it lacks, each a TODO.\n\"\"\"\n\n\
         from __future__ import annotations\n\n"
    );
    out.push_str(&interface_imports(app, component));
    out.push_str(&format!(
        "from {}.{} import {name}\n\n\nclass {name}Impl({name}):\n",
        app.package(),
        snake(name)
    ));
    let body: Vec<String> = methods(component).iter().map(stub).collect();
    out.push_str(&body.join("\n"));
    out
}

/// An implementation method: its signature and a TODO body.
fn stub(method: &Method) -> String {
    format!(
        "{}\n        raise NotImplementedError  # TODO: {}\n",
        signature(4, method, ""),
        method.todo
    )
}

/// `head(args)` at `indent`, on one line when it fits, else black's
/// right-hand split.
fn call(indent: usize, head: &str, args: &str) -> String {
    let pad = " ".repeat(indent);
    let line = format!("{pad}{head}({args})\n");
    if line.len() <= WIDTH + 1 {
        return line;
    }
    format!("{pad}{head}(\n{pad}    {args}\n{pad})\n")
}

fn dispatch(app: &PythonApp, component: &Component) -> String {
    let name = &component.name;
    let stem = snake(name);
    let package = app.package();
    let mut modules = BTreeSet::new();
    modules.insert((pb2_module(app, &component.anchor), alias(&component.anchor)));
    for input in &component.inputs {
        modules.insert((pb2_module(app, &input.message), alias(&input.message)));
    }
    for event in &component.events {
        modules.insert((pb2_module(app, event), alias(event)));
    }
    let mut out = format!(
        "{GENERATED}\"\"\"The {name}'s dispatch for the router binding: each entry decodes\n\
         the wire payload and calls the ``{name}`` interface with the domain's\n\
         messages, and packs what it returns (one event, an iterable of events, or\n\
         None) into the event book.\n\"\"\"\n\n\
         from __future__ import annotations\n\n\
         import angzarr_client.router as _az\n\
         from angzarr_client.proto.io.angzarr.v1 import types_pb2 as _t\n\
         from google.protobuf import message as _message\n\n"
    );
    for (module, alias) in &modules {
        let (parent, leaf) = module.rsplit_once('.').unwrap_or(("", module));
        out.push_str(&format!("from {parent} import {leaf} as {alias}\n"));
    }
    out.push_str(&format!("from {package}.{stem} import {name}\n"));
    out.push_str(
        "\n\ndef _decode(message, payload):\n    try:\n        message.ParseFromString(payload.value)\n    except Exception as exc:\n        raise _az.any_decode_error(payload.type_url, exc)\n    return message\n\n\n\
         def _book(result) -> _t.EventBook:\n    if result is None:\n        events = ()\n    elif isinstance(result, _message.Message):\n        events = (result,)\n    else:\n        events = result\n    book = _t.EventBook()\n    for event in events:\n        book.pages.add().payload.CopyFrom(_az.pack(event))\n    return book\n\n\n",
    );
    let state = format!("{}.{}", alias(&component.anchor), component.anchor.name());
    out.push_str(&format!(
        "def new_{stem}_dispatch(impl: {name}) -> _az.AggregateDispatch:\n    rebuilder = _az.Rebuilder({state})\n"
    ));
    for event in &component.events {
        let method = format!("apply_{}", snake(event.name()));
        out.push_str(&format!(
            "\n    def _{method}(state, payload, ctx):\n        impl.{method}(_decode({}.{}(), payload), state)\n\n",
            alias(event),
            event.name()
        ));
        out.push_str(&call(
            4,
            "rebuilder.apply_with_context",
            &format!("\"{}\", _{method}", event.full_name()),
        ));
    }
    out.push_str(&format!(
        "\n    dispatch = _az.AggregateDispatch(\"{name}\", \"{}\", rebuilder)\n",
        component.domain
    ));
    for input in &component.inputs {
        let method = snake(input.message.name());
        out.push_str(&format!(
            "\n    def _on_{method}(payload, state, cctx):\n        return _book(impl.{method}(_decode({}.{}(), payload), state))\n\n",
            alias(&input.message),
            input.message.name()
        ));
        out.push_str(&call(
            4,
            "dispatch.on_command",
            &format!("\"{}\", _on_{method}", input.message.full_name()),
        ));
    }
    out.push_str("    return dispatch\n");
    out
}

fn main_py(app: &PythonApp, components: &[Component]) -> String {
    let package = app.package();
    let script = app.script();
    let domain = &app.domain;
    let mut imports = Vec::new();
    let mut registers = Vec::new();
    for component in components {
        let name = &component.name;
        let stem = snake(name);
        let dir = module_dir(&component.anchor).replace('/', ".");
        imports.push(format!(
            "from {package}._gen.{dir}.{stem}_angzarr import (\n    new_{stem}_dispatch,\n)\n"
        ));
        imports.push(format!("from {package}.{stem}_impl import {name}Impl\n"));
        registers.push(format!("new_{stem}_dispatch({name}Impl())"));
    }
    imports.push(format!("from {package}._version import __version__\n"));
    imports.sort();
    let names: Vec<&str> = components.iter().map(|c| c.name.as_str()).collect();
    let mut chain = String::from("host");
    for register in &registers {
        chain = format!("{chain}.add_aggregate({register})");
    }
    let lead = names
        .first()
        .map(|n| format!("{n}Impl"))
        .unwrap_or_default();
    format!(
        "{GENERATED}\"\"\"{script}: the {domain} domain as an angzarr-embedded child process.\n\n\
         angzarr-embedded launches it (``uv run --locked {script}``), reads the\n\
         handshake it writes once it is serving, and calls it over gRPC on a Unix\n\
         socket. The logic is ``{lead}``'s; nothing here is yours.\n\"\"\"\n\n\
         from __future__ import annotations\n\n\
         from angzarr_client import ComponentHost, configure_logging\n\
         from angzarr_client.child import run_child\n\n\
         {}\n\n\
         def register(host: ComponentHost) -> ComponentHost:\n    \"\"\"The {} on ``host``.\"\"\"\n    return {chain}\n\n\n\
         def host() -> ComponentHost:\n    \"\"\"The child's host, reporting ``_version`` as its rules_version.\"\"\"\n    return register(ComponentHost(rules_version=__version__))\n\n\n\
         def main() -> None:\n    configure_logging()\n    run_child(host())\n",
        imports.concat(),
        names.join(", "),
    )
}

