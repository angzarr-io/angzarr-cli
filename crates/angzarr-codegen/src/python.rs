const COMMAND_OPTION: &str = "io.angzarr.v1.command";
const COMPONENT_DESCRIPTOR: &str = "io.angzarr.v1.ComponentDescriptor";
/// `EmitsCardinality`'s numbers (options.proto).
const OPTIONAL: i32 = 2;
const MANY: i32 = 3;

/// Where `buf generate` reads the domain's protos from.
#[derive(Clone, PartialEq, Eq, Debug)]
pub enum ProtoInput {
    /// A git repository at a revision, the protos under its `proto`, as
    /// angzarr-project lays them out.
    Git { url: String, rev: String },
    /// A directory, relative to the project root (where buf runs) or
    /// absolute.
    Directory(String),
}

/// One Python component's project.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct PythonApp {
    /// What the project serves: a domain (its aggregate's or process
    /// manager's, e.g. `player`), or a component's name in an application
    /// (`component_name`, else its kind's default: `policy-table-player`,
    /// `projector-wallet-table-ledger`). The package is `angzarr_<domain>`,
    /// the distribution and its script `angzarr-<domain>`.
    pub domain: String,
    pub protos: ProtoInput,
    /// The build version the component reports as its rules_version.
    pub rules_version: String,
}

impl PythonApp {
    fn package(&self) -> String {
        format!("angzarr_{}", self.domain.replace('-', "_"))
    }

    fn script(&self) -> String {
        format!("angzarr-{}", self.domain.replace('_', "-"))
    }
}

/// How many events one handling of an input emits
/// (`CommandOptions.emits_cardinality`).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Cardinality {
    /// One of each emits type: the event, or a tuple of several.
    One,
    /// That, or nothing.
    Optional,
    /// Any number of any of them.
    Many,
}

/// One component as the Python scaffold emits it.
struct Unit {
    component: Component,
    /// Its name in an application: its `component_name`, else its kind's
    /// default.
    name: String,
    /// A policy's target's commands: what its reactions send.
    commands: Vec<MessageDescriptor>,
    /// A projector's source domains.
    sources: Vec<String>,
}

impl Unit {
    fn kind(&self) -> ComponentKind {
        self.component.kind
    }

    /// A domain: an aggregate or a process manager, deciding inputs and
    /// folding its events.
    fn is_domain(&self) -> bool {
        matches!(
            self.kind(),
            ComponentKind::Aggregate | ComponentKind::ProcessManager
        )
    }
}

/// The project of `app.domain`: the component of that domain, or of that
/// name, declared in `files`, as the files listed in the module doc. Paths
/// are relative to the project root.
pub fn scaffold_python(
    descriptor_set: &[u8],
    files: &[&str],
    app: &PythonApp,
) -> Result<Vec<ScaffoldFile>, CodegenError> {
    let components: Vec<Component> = model::components(descriptor_set, files, DESCRIPTOR_KINDS)?
        .into_iter()
        .filter(|c| c.domain == app.domain || component_name(c) == app.domain)
        .collect();
    if components.is_empty() {
        return Err(CodegenError::PythonNoDomain {
            domain: app.domain.clone(),
        });
    }
    let units = components
        .into_iter()
        .map(|c| unit(c, descriptor_set))
        .collect::<Result<Vec<_>, _>>()?;
    for unit in &units {
        let (messages, enums) = reached(unit);
        let names: Vec<(&str, String)> = messages
            .iter()
            .map(|m| (m.full_name(), local_name(m.full_name(), m.package_name())))
            .chain(
                enums
                    .iter()
                    .map(|e| (e.full_name(), local_name(e.full_name(), e.package_name()))),
            )
            .collect();
        model::refuse_reserved(names.iter().cloned())?;
        if let Some((full, local)) = names
            .into_iter()
            .find(|(_, local)| PYTHON_RESERVED.contains(&local.as_str()))
        {
            return Err(CodegenError::ReservedName {
                message: full.to_string(),
                name: local,
            });
        }
    }
    let package = app.package();
    let src = format!("src/{package}");
    let anchor = units[0].component.anchor.full_name().to_string();
    let file = |path: String, source: String, owner: Owner| ScaffoldFile {
        component: anchor.clone(),
        path,
        source,
        owner,
    };
    let served = served(app, &units[0]);

    let mut out = vec![
        file(
            "pyproject.toml".to_string(),
            pyproject(app, &served, &units),
            Owner::User,
        ),
        file(
            "buf.gen.yaml".to_string(),
            buf_gen(app, &served, &units),
            Owner::Generated,
        ),
        file(format!("{src}/__init__.py"), String::new(), Owner::User),
        file(
            format!("{src}/__main__.py"),
            format!("{GENERATED}\nfrom {package}.main import main\n\nmain()\n"),
            Owner::Generated,
        ),
        file(
            format!("{src}/_version.py"),
            format!(
                "{GENERATED}\"\"\"The build version {served} reports as its rules_version.\"\"\"\n\n__version__ = {:?}\n",
                app.rules_version
            ),
            Owner::Generated,
        ),
        file(
            format!("{src}/main.py"),
            main_py(app, &served, &units),
            Owner::Generated,
        ),
        file(
            format!("{src}/_descriptor.py"),
            descriptor_py(app, &served, descriptor_set, files, &units[0])?,
            Owner::Generated,
        ),
        file("tests/__init__.py".to_string(), String::new(), Owner::User),
    ];
    let mut packages = BTreeSet::new();
    for unit in &units {
        let component = &unit.component;
        let dir = module_dir(&component.anchor);
        let mut path = String::new();
        for part in std::iter::once("_gen").chain(dir.split('/')) {
            if !path.is_empty() {
                path.push('/');
            }
            path.push_str(part);
            packages.insert(path.clone());
        }
        let stem = snake(&component.name);
        let own = |path: String, source: String, owner: Owner| ScaffoldFile {
            component: component.anchor.full_name().to_string(),
            path,
            source,
            owner,
        };
        out.push(own(
            format!("{src}/logic.py"),
            interface(app, unit),
            Owner::User,
        ));
        out.push(own(
            format!("{src}/logic_impl.py"),
            implementation(app, unit),
            Owner::User,
        ));
        out.push(own(
            format!("{src}/domain.py"),
            domain_py(&served, unit),
            Owner::Generated,
        ));
        out.push(own(
            format!("{src}/_gen/{dir}/{stem}_angzarr.py"),
            dispatch(app, unit),
            Owner::Generated,
        ));
    }
    for dir in packages {
        out.push(file(
            format!("{src}/{dir}/__init__.py"),
            GENERATED.to_string(),
            Owner::Generated,
        ));
    }
    out.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(out)
}

/// `component` with what its kind needs beside it: a policy's target's
/// commands (refused when no aggregate or process manager of the set owns
/// its `output_domain`), a projector's sources.
fn unit(component: Component, descriptor_set: &[u8]) -> Result<Unit, CodegenError> {
    let mut commands = Vec::new();
    if component.kind == ComponentKind::Policy {
        let pool = model::pool_components(descriptor_set)?;
        let target = pool
            .iter()
            .find(|t| t.kind != ComponentKind::Policy && t.domain == component.output_domain)
            .ok_or_else(|| CodegenError::UnownedDomain {
                policy: component.anchor.full_name().to_string(),
                domain: component.output_domain.clone(),
            })?;
        commands = target
            .inputs
            .iter()
            .filter(|i| !i.fact)
            .map(|i| i.message.clone())
            .collect();
    }
    let sources = if component.kind == ComponentKind::Projector {
        projector_sources(&component)
    } else {
        Vec::new()
    };
    Ok(Unit {
        name: component_name(&component),
        component,
        commands,
        sources,
    })
}

/// A message's angzarr option `extension`, when it declares one.
fn declared(message: &MessageDescriptor, extension: &str) -> Option<DynamicMessage> {
    let ext = message.parent_pool().get_extension_by_name(extension)?;
    let options = message.options();
    if !options.has_extension(&ext) {
        return None;
    }
    match options.get_extension(&ext).into_owned() {
        Value::Message(m) => Some(m),
        _ => None,
    }
}

/// A field of a declared option; `None` when unset or unknown to the set's
/// options.proto.
fn declared_field(message: &MessageDescriptor, extension: &str, field: &str) -> Option<Value> {
    let option = declared(message, extension)?;
    option.get_field_by_name(field).map(|v| v.into_owned())
}

/// The component's name in an application (decision 14.50): its
/// `component_name`, else by kind its domain (an aggregate), `pmg-` and
/// its domain (a process manager), `policy-<input>-<output>` (a policy)
/// or `projector-` and its anchor's name in kebab case (a projector).
fn component_name(component: &Component) -> String {
    if let Some(Value::String(name)) =
        declared_field(&component.anchor, COMPONENT_OPTION, "component_name")
        && !name.is_empty()
    {
        return name;
    }
    match component.kind {
        ComponentKind::Aggregate => component.domain.clone(),
        ComponentKind::ProcessManager => format!("pmg-{}", component.domain),
        ComponentKind::Policy => format!(
            "policy-{}-{}",
            component.input_domain, component.output_domain
        ),
        ComponentKind::Projector => {
            format!(
                "projector-{}",
                snake(component.anchor.name()).replace('_', "-")
            )
        }
    }
}

/// A projector's source domains: its `input_domains`, else its
/// `input_domain`, else the domains its `(event)` entries name.
fn projector_sources(component: &Component) -> Vec<String> {
    let listed: Vec<String> =
        match declared_field(&component.anchor, COMPONENT_OPTION, "input_domains") {
            Some(Value::List(values)) => values
                .iter()
                .filter_map(|v| v.as_str().map(str::to_string))
                .collect(),
            _ => Vec::new(),
        };
    if !listed.is_empty() {
        listed
    } else if !component.input_domain.is_empty() {
        vec![component.input_domain.clone()]
    } else {
        component.sources.clone()
    }
}

/// An input's emits cardinality: unset is one.
fn cardinality(input: &Input) -> Cardinality {
    match declared_field(&input.message, COMMAND_OPTION, "emits_cardinality") {
        Some(Value::EnumNumber(OPTIONAL)) => Cardinality::Optional,
        Some(Value::EnumNumber(MANY)) => Cardinality::Many,
        _ => Cardinality::One,
    }
}

/// What the project serves, for its docs: `the player domain`, `the
/// policy-table-player policy`.
fn served(app: &PythonApp, unit: &Unit) -> String {
    match unit.kind() {
        ComponentKind::Aggregate | ComponentKind::ProcessManager => {
            format!("the {} domain", app.domain)
        }
        ComponentKind::Policy => format!("the {} policy", unit.name),
        ComponentKind::Projector => format!("the {} projector", unit.name),
    }
}

/// `served` with its first letter upper-cased.
fn capital(served: &str) -> String {
    let mut chars = served.chars();
    chars
        .next()
        .map(|c| c.to_ascii_uppercase().to_string() + chars.as_str())
        .unwrap_or_default()
}

/// `_descriptor.py`: the unit's generated `ComponentDescriptor`, named by
/// its name in an application, `app.rules_version` its rules version, as
/// the bytes its child answers `Describe` with, unchanged.
fn descriptor_py(
    app: &PythonApp,
    served: &str,
    descriptor_set: &[u8],
    files: &[&str],
    unit: &Unit,
) -> Result<String, CodegenError> {
    let anchor = unit.component.anchor.full_name();
    let encoded = crate::descriptor::descriptors(descriptor_set, files, &app.rules_version)?
        .into_iter()
        .find(|d| d.component == anchor)
        .map(|d| d.encoded)
        .unwrap_or_default();
    let encoded = renamed(descriptor_set, &encoded, &unit.name)?;
    let hex: String = encoded.iter().map(|b| format!("{b:02x}")).collect();
    let lines: String = hex
        .as_bytes()
        .chunks(64)
        .map(|chunk| format!("        \"{}\"\n", String::from_utf8_lossy(chunk)))
        .collect();
    Ok(format!(
        "{GENERATED}\"\"\"{}'s ComponentDescriptor, generated from its protos.\n\n\
         Its rules_version is ``_version``'s. The child answers ``Describe`` with it,\n\
         unchanged (decision 14.42).\n\
         \"\"\"\n\n\
         from __future__ import annotations\n\n\
         from angzarr_client.proto.io.angzarr.v1 import types_pb2 as _t\n\n\
         DESCRIPTOR = _t.ComponentDescriptor.FromString(\n    bytes.fromhex(\n{lines}    )\n)\n",
        capital(served),
    ))
}

/// `encoded`, a `ComponentDescriptor`, named `name`.
fn renamed(descriptor_set: &[u8], encoded: &[u8], name: &str) -> Result<Vec<u8>, CodegenError> {
    let failed = |detail: String| CodegenError::Descriptors { detail };
    let pool = DescriptorPool::decode(descriptor_set).map_err(|e| failed(e.to_string()))?;
    let descriptor = pool
        .get_message_by_name(COMPONENT_DESCRIPTOR)
        .ok_or_else(|| failed(format!("the set declares no {COMPONENT_DESCRIPTOR}")))?;
    let mut message =
        DynamicMessage::decode(descriptor, encoded).map_err(|e| failed(e.to_string()))?;
    message.set_field_by_name("name", Value::String(name.to_string()));
    Ok(message.encode_to_vec())
}

/// `io/angzarr/examples/v1` for a message of `io/angzarr/examples/v1/x.proto`.
fn module_dir(message: &MessageDescriptor) -> String {
    let name = message.parent_file().name().to_string();
    name.rsplit_once('/')
        .map_or(String::new(), |(dir, _)| dir.to_string())
}

/// The dotted module of a message's pb2, under the project's `_gen`.
fn pb2_module(app: &PythonApp, message: &MessageDescriptor) -> String {
    let name = message.parent_file().name().to_string();
    let stem = name.trim_end_matches(".proto").replace('/', ".");
    format!("{}._gen.{stem}_pb2", app.package())
}

/// The pb2 alias the dispatch imports a message's module as: `_<stem>`.
fn alias(message: &MessageDescriptor) -> String {
    let name = message.parent_file().name().to_string();
    let stem = name
        .rsplit('/')
        .next()
        .unwrap_or(&name)
        .trim_end_matches(".proto");
    format!("_{stem}")
}

/// One method of the logic interface.
struct Method {
    name: String,
    /// A coroutine: `async def`.
    asynchronous: bool,
    /// `(param, type)`, after `self`.
    params: Vec<(String, String)>,
    returns: String,
    todo: String,
}

/// The interface's name: a domain's, camel-cased, then `Logic` (`player`
/// as `PlayerLogic`); a policy's or a projector's code name, then `Logic`
/// (`LedgerProjectorLogic`).
fn logic_name(app: &PythonApp, unit: &Unit) -> String {
    if !unit.is_domain() {
        return format!("{}Logic", unit.component.name);
    }
    let camel: String = app
        .domain
        .split(['_', '-'])
        .filter(|w| !w.is_empty())
        .map(|w| {
            let mut chars = w.chars();
            chars
                .next()
                .map(|c| c.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect();
    format!("{camel}Logic")
}

/// What a decision of `input` returns: its events by its cardinality (one
/// event, a tuple of several, that or None, or a list of any of them;
/// None when it emits nothing), or one of its typed refusals.
fn decided(input: &Input) -> String {
    let names: Vec<&str> = input.emits.iter().map(|e| e.name()).collect();
    let events = match (cardinality(input), names.as_slice()) {
        (_, []) => "None".to_string(),
        (Cardinality::Many, _) => format!("list[{}]", names.join(" | ")),
        (Cardinality::Optional, [one]) => format!("{one} | None"),
        (Cardinality::Optional, _) => format!("tuple[{}] | None", names.join(", ")),
        (Cardinality::One, [one]) => one.to_string(),
        (Cardinality::One, _) => format!("tuple[{}]", names.join(", ")),
    };
    std::iter::once(events)
        .chain(input.refuses.iter().map(|r| r.name().to_string()))
        .collect::<Vec<_>>()
        .join(" | ")
}

/// The interface's methods, by kind. A domain's: a decision per command
/// (or fact) from the state and its context (the harness's
/// `CommandContext`, re-exported by `domain.py`), returning what it emits
/// or a typed refusal, and a fold per event from the state to the next
/// state. A policy's: a reaction per event from the event, its source root
/// and its page's context, returning the target's commands, each with its
/// root. A projector's: a coroutine per event from the projection, the
/// event and its page's context, returning the next projection. All of it
/// in the plain types (`domain.py`).
fn methods(unit: &Unit) -> Vec<Method> {
    let component = &unit.component;
    let anchor = component.anchor.name().to_string();
    let mut out = Vec::new();
    match component.kind {
        ComponentKind::Aggregate | ComponentKind::ProcessManager => {
            for input in &component.inputs {
                let ty = input.message.name().to_string();
                let param = if input.fact { "fact" } else { "cmd" };
                out.push(Method {
                    name: snake(&ty),
                    asynchronous: false,
                    params: vec![
                        (param.to_string(), ty.clone()),
                        ("state".to_string(), anchor.clone()),
                        ("ctx".to_string(), "CommandContext".to_string()),
                    ],
                    returns: decided(input),
                    todo: if input.fact {
                        format!("record {ty}")
                    } else {
                        format!("decide {ty}")
                    },
                });
            }
            for event in &component.events {
                let ty = event.name().to_string();
                out.push(Method {
                    name: format!("apply_{}", snake(&ty)),
                    asynchronous: false,
                    params: vec![
                        ("state".to_string(), anchor.clone()),
                        ("event".to_string(), ty.clone()),
                    ],
                    returns: anchor.clone(),
                    todo: format!("fold {ty} into the state"),
                });
            }
        }
        ComponentKind::Policy => {
            let commands: Vec<&str> = unit.commands.iter().map(|c| c.name()).collect();
            let command = match commands.as_slice() {
                [] => "object".to_string(),
                _ => commands.join(" | "),
            };
            for event in &component.events {
                let ty = event.name().to_string();
                out.push(Method {
                    name: snake(&ty),
                    asynchronous: false,
                    params: vec![
                        ("event".to_string(), ty.clone()),
                        ("source".to_string(), "bytes".to_string()),
                        ("ctx".to_string(), "PageContext".to_string()),
                    ],
                    returns: format!("list[tuple[bytes, {command}]]"),
                    todo: format!("react to {ty}"),
                });
            }
        }
        ComponentKind::Projector => {
            for event in &component.events {
                let ty = event.name().to_string();
                out.push(Method {
                    name: format!("project_{}", snake(&ty)),
                    asynchronous: true,
                    params: vec![
                        ("projection".to_string(), anchor.clone()),
                        ("event".to_string(), ty.clone()),
                        ("ctx".to_string(), "PageContext".to_string()),
                    ],
                    returns: anchor.clone(),
                    todo: format!("project {ty}"),
                });
            }
        }
    }
    out
}

/// The import of the plain types the interface names.
fn interface_imports(app: &PythonApp, unit: &Unit) -> String {
    let component = &unit.component;
    let mut names = BTreeSet::new();
    if component.kind != ComponentKind::Policy {
        names.insert(component.anchor.name().to_string());
    }
    if unit.is_domain() {
        if !component.inputs.is_empty() {
            names.insert("CommandContext".to_string());
        }
    } else if !component.events.is_empty() {
        names.insert("PageContext".to_string());
    }
    for input in &component.inputs {
        names.insert(input.message.name().to_string());
        names.extend(input.emits.iter().map(|e| e.name().to_string()));
        names.extend(input.refuses.iter().map(|r| r.name().to_string()));
    }
    names.extend(component.events.iter().map(|e| e.name().to_string()));
    if !component.events.is_empty() {
        names.extend(unit.commands.iter().map(|c| c.name().to_string()));
    }
    let mut out = format!("from {}.domain import (\n", app.package());
    for name in names {
        out.push_str(&format!("    {name},\n"));
    }
    out.push_str(")\n");
    out
}

/// `def name(self, a: A, b: B) -> R:` laid out as black lays it out at
/// `indent`, followed by `tail` (` ...` or nothing).
fn signature(indent: usize, method: &Method, tail: &str) -> String {
    let params: Vec<String> = std::iter::once("self".to_string())
        .chain(method.params.iter().map(|(p, t)| format!("{p}: {t}")))
        .collect();
    let def = if method.asynchronous {
        "async def"
    } else {
        "def"
    };
    head(
        indent,
        &format!("{def} {}", method.name),
        &params,
        &method.returns,
        tail,
    )
}

/// `{def}({params}) -> {returns}:{tail}` at `indent`: on one line when it
/// fits, else its parameters on one line of their own, else one a line.
fn head(indent: usize, def: &str, params: &[String], returns: &str, tail: &str) -> String {
    let pad = " ".repeat(indent);
    let line = format!("{pad}{def}({}) -> {returns}:{tail}", params.join(", "));
    if line.len() <= WIDTH {
        return line;
    }
    let inner = format!("{pad}    {}", params.join(", "));
    if inner.len() <= WIDTH && params.len() > 1 {
        return format!("{pad}{def}(\n{inner}\n{pad}) -> {returns}:{tail}");
    }
    let exploded: String = params.iter().map(|p| format!("{pad}    {p},\n")).collect();
    format!("{pad}{def}(\n{exploded}{pad}) -> {returns}:{tail}")
}

/// What the logic does, for the interface's doc, by kind.
fn duties(unit: &Unit) -> &'static str {
    match unit.kind() {
        ComponentKind::Aggregate | ComponentKind::ProcessManager => {
            "each decision its ``CommandContext`` too, returning its events or one of \
             its typed refusals, or raising ``Rejection`` to refuse its command \
             (or ``Bug`` for a defect),"
        }
        ComponentKind::Policy => {
            "each reaction its event's source root and ``PageContext`` too, returning \
             the commands it sends, each with its target root (raising ``Bug`` for a \
             defect),"
        }
        ComponentKind::Projector => {
            "each projection a coroutine, its event's ``PageContext`` too (the source \
             domain is its cover's), returning the next projection (raising ``Bug`` \
             for a defect),"
        }
    }
}

fn interface(app: &PythonApp, unit: &Unit) -> String {
    let component = &unit.component;
    let name = logic_name(app, unit);
    let owner = match unit.kind() {
        ComponentKind::Aggregate | ComponentKind::ProcessManager => {
            format!("the {} domain's logic", app.domain)
        }
        ComponentKind::Policy => format!("the {} policy's logic", unit.name),
        ComponentKind::Projector => format!("the {} projector's logic", unit.name),
    };
    let doc = wrap(&format!(
        "\"\"\"{name}: {owner}, for ``{}``. Written once by \
         ``angzarr scaffold python`` and yours from then on: ``--missing`` adds the methods \
         it lacks. It takes and returns the plain types (:mod:`.domain`), {} \
         and imports nothing of angzarr directly; the generated dispatch \
         (``_gen/.../{}_angzarr.py``) calls it.",
        component.anchor.full_name(),
        duties(unit),
        snake(&component.name),
    ));
    let mut out = format!(
        "{doc}\n\"\"\"\n\nfrom __future__ import annotations\n\nfrom typing import Protocol\n\n"
    );
    out.push_str(&interface_imports(app, unit));
    out.push_str(&format!("\n\nclass {name}(Protocol):\n"));
    let body: Vec<String> = methods(unit)
        .iter()
        .map(|m| format!("{}\n", signature(4, m, " ...")))
        .collect();
    out.push_str(&body.join("\n"));
    out
}

fn implementation(app: &PythonApp, unit: &Unit) -> String {
    let name = logic_name(app, unit);
    let mut out = format!(
        "\"\"\"{name}Impl: the implementation of ``{name}``, written once by\n\
         ``angzarr scaffold python`` and yours from then on: ``--missing`` adds the\n\
         methods it lacks, each a TODO.\n\"\"\"\n\n\
         from __future__ import annotations\n\n"
    );
    out.push_str(&interface_imports(app, unit));
    out.push_str(&format!(
        "from {}.logic import {name}\n\n\nclass {name}Impl({name}):\n",
        app.package(),
    ));
    let body: Vec<String> = methods(unit).iter().map(stub).collect();
    out.push_str(&body.join("\n"));
    out
}

/// `text` wrapped at 79 columns, on spaces.
fn wrap(text: &str) -> String {
    let mut lines: Vec<String> = vec![String::new()];
    for word in text.split(' ') {
        let line = lines.last_mut().expect("a line");
        if !line.is_empty() && line.len() + 1 + word.len() > 79 {
            lines.push(word.to_string());
        } else {
            if !line.is_empty() {
                line.push(' ');
            }
            line.push_str(word);
        }
    }
    lines.join("\n")
}

/// An implementation method: its signature and a TODO body.
fn stub(method: &Method) -> String {
    format!(
        "{}\n        raise NotImplementedError  # TODO: {}\n",
        signature(4, method, ""),
        method.todo
    )
}

/// `head(args)` at `indent`, on one line when it fits, else black's
/// right-hand split.
fn call(indent: usize, head: &str, args: &str) -> String {
    let pad = " ".repeat(indent);
    let line = format!("{pad}{head}({args})\n");
    if line.len() <= WIDTH + 1 {
        return line;
    }
    format!("{pad}{head}(\n{pad}    {args}\n{pad})\n")
}

/// The messages the plain types start from: a domain's state, inputs,
/// what they emit and refuse, and its events; a policy's events and its
/// target's commands; a projector's projection and its events.
fn roots(unit: &Unit) -> Vec<MessageDescriptor> {
    let component = &unit.component;
    let mut roots = Vec::new();
    if component.kind != ComponentKind::Policy {
        roots.push(component.anchor.clone());
    }
    for input in &component.inputs {
        roots.push(input.message.clone());
        roots.extend(input.emits.iter().cloned());
        roots.extend(input.refuses.iter().cloned());
    }
    roots.extend(component.events.iter().cloned());
    roots.extend(unit.commands.iter().cloned());
    roots
}

/// A field's kind, a map's by its value.
fn element_kind(field: &prost_reflect::FieldDescriptor) -> Kind {
    match field.kind() {
        Kind::Message(entry) if entry.is_map_entry() => entry.map_entry_value_field().kind(),
        kind => kind,
    }
}

/// Every message and enum of the unit's plain types, every one its
/// [`roots`] reach, in the order they are reached; angzarr's own and
/// google's excepted.
fn reached(unit: &Unit) -> (Vec<MessageDescriptor>, Vec<EnumDescriptor>) {
    let mut messages: Vec<MessageDescriptor> = Vec::new();
    let mut enums: Vec<EnumDescriptor> = Vec::new();
    let foreign =
        |package: &str| FRAMEWORK_PACKAGES.contains(&package) || package.starts_with("google.");
    let mut queue = roots(unit);
    let mut i = 0;
    while i < queue.len() {
        let message = queue[i].clone();
        i += 1;
        if messages.contains(&message) || foreign(message.package_name()) {
            continue;
        }
        for field in message.fields() {
            match element_kind(&field) {
                Kind::Message(m) => queue.push(m),
                Kind::Enum(e) if !foreign(e.package_name()) && !enums.contains(&e) => enums.push(e),
                _ => {}
            }
        }
        messages.push(message);
    }
    (messages, enums)
}

/// A Python name for a proto name: itself, `_` appended where it is a
/// keyword.
fn py_name(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class",
        "continue", "def", "del", "elif", "else", "except", "finally", "for", "from", "global",
        "if", "import", "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return",
        "try", "while", "with", "yield",
    ];
    if KEYWORDS.contains(&name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

/// A nested type's plain name: its enclosing messages' names, then its own.
fn local_name(full: &str, package: &str) -> String {
    full.strip_prefix(package)
        .map_or(full, |rest| rest.trim_start_matches('.'))
        .replace('.', "")
}

/// `MOVE_ACTION_HIT` of `MoveAction` as `HIT`.
fn member(e: &EnumDescriptor, value: &str) -> String {
    let mut prefix = String::new();
    for (i, c) in e.name().chars().enumerate() {
        if c.is_ascii_uppercase() && i > 0 {
            prefix.push('_');
        }
        prefix.push(c.to_ascii_uppercase());
    }
    prefix.push('_');
    py_name(value.strip_prefix(&prefix).unwrap_or(value))
}

/// The plain type of one value of `kind`, and its zero where it has one.
fn value_type(kind: &Kind) -> (String, Option<String>) {
    match kind {
        Kind::Message(m) => (local_name(m.full_name(), m.package_name()), None),
        Kind::Enum(e) => {
            let name = local_name(e.full_name(), e.package_name());
            let zero = e
                .values()
                .find(|v| v.number() == 0)
                .map(|v| format!("{name}.{}", member(e, v.name())));
            (name, zero)
        }
        Kind::Double | Kind::Float => ("float".to_string(), Some("0.0".to_string())),
        Kind::Bool => ("bool".to_string(), Some("False".to_string())),
        Kind::String => ("str".to_string(), Some("\"\"".to_string())),
        Kind::Bytes => ("bytes".to_string(), Some("b\"\"".to_string())),
        _ => ("int".to_string(), Some("0".to_string())),
    }
}

/// A field's plain type and its default.
fn field_type(field: &prost_reflect::FieldDescriptor) -> (String, String) {
    if let Kind::Message(entry) = field.kind()
        && entry.is_map_entry()
    {
        let (key, _) = value_type(&entry.map_entry_key_field().kind());
        let (value, _) = value_type(&entry.map_entry_value_field().kind());
        return (
            format!("dict[{key}, {value}]"),
            "field(default_factory=dict)".to_string(),
        );
    }
    let (ty, zero) = value_type(&field.kind());
    if field.is_list() {
        return (format!("tuple[{ty}, ...]"), "()".to_string());
    }
    match zero {
        Some(zero) if !field.supports_presence() => (ty, zero),
        _ => (format!("{ty} | None"), "None".to_string()),
    }
}

