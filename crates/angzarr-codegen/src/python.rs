/// Every proto file the units' plain types reach, angzarr's own and
/// google's excepted.
fn proto_paths(units: &[Unit]) -> BTreeSet<String> {
    let mut seen = BTreeSet::new();
    let mut files = BTreeSet::new();
    let mut stack: Vec<MessageDescriptor> = units.iter().flat_map(roots).collect();
    while let Some(message) = stack.pop() {
        if !seen.insert(message.full_name().to_string()) {
            continue;
        }
        let package = message.package_name().to_string();
        if !FRAMEWORK_PACKAGES.contains(&package.as_str()) && !package.starts_with("google.") {
            files.insert(message.parent_file().name().to_string());
        }
        for field in message.fields() {
            match field.kind() {
                Kind::Message(m) => stack.push(m),
                Kind::Enum(e) => {
                    let package = e.package_name().to_string();
                    if !FRAMEWORK_PACKAGES.contains(&package.as_str())
                        && !package.starts_with("google.")
                    {
                        files.insert(e.parent_file().name().to_string());
                    }
                }
                _ => {}
            }
        }
    }
    files
}

fn buf_gen(app: &PythonApp, served: &str, units: &[Unit]) -> String {
    let package = app.package();
    // A git input's paths are under its `proto`; a directory's are buf's
    // `--path`s, relative to where buf runs (the project root), as the
    // directory is.
    let (input, under) = match &app.protos {
        ProtoInput::Git { url, rev } => (
            format!("  - git_repo: {url}\n    ref: {rev}\n    subdir: proto\n"),
            String::new(),
        ),
        ProtoInput::Directory(dir) => (format!("  - directory: {dir}\n"), format!("{dir}/")),
    };
    let paths: String = proto_paths(units)
        .iter()
        .map(|p| format!("      - {under}{p}\n"))
        .collect();
    format!(
        "{GENERATED}#\n\
         # {}'s message types (pb2 and pyi) into\n\
         # src/{package}/_gen: its protos and the ones they import, never\n\
         # angzarr's own (those are angzarr_client.proto's). The dispatch beside them\n\
         # is the angzarr CLI's, and so is the rerooting of their imports.\n\
         version: v2\n\
         inputs:\n{input}    paths:\n{paths}\
         plugins:\n\
         \x20 - remote: buf.build/protocolbuffers/python:v35.1\n    out: src/{package}/_gen\n\
         \x20 - remote: buf.build/protocolbuffers/pyi:v35.1\n    out: src/{package}/_gen\n",
        capital(served),
    )
}

/// The import rules for generated message types: angzarr's framework
/// packages from `angzarr_client.proto`, every other package from the
/// project's `_gen`.
pub fn python_reroots(app: &PythonApp, packages: &[&str]) -> Vec<(String, String)> {
    let mut rules: Vec<(String, String)> = FRAMEWORK_PACKAGES
        .iter()
        .map(|p| (p.to_string(), format!("angzarr_client.proto.{p}")))
        .collect();
    for package in packages {
        if !FRAMEWORK_PACKAGES.contains(package) {
            rules.push((
                package.to_string(),
                format!("{}._gen.{package}", app.package()),
            ));
        }
    }
    rules
}

/// `source`, a generated pb2 or pyi module, with each import of a module
/// under a rule's package rerooted to the rule's target: `from io.angzarr.v1
/// import x` and `import io.angzarr.v1.x` alike. Nothing else changes.
pub fn reroot_python(source: &str, rules: &[(String, String)]) -> String {
    // The longest package a line names wins: `io.angzarr.v1` is not `io`.
    let mut rules: Vec<&(String, String)> = rules.iter().collect();
    rules.sort_by_key(|(from, _)| std::cmp::Reverse(from.len()));
    let mut out = String::with_capacity(source.len());
    for line in source.split_inclusive('\n') {
        let mut rewritten = None;
        for (from, to) in &rules {
            for keyword in ["from ", "import "] {
                let Some(rest) = line.strip_prefix(keyword) else {
                    continue;
                };
                let Some(after) = rest.strip_prefix(from.as_str()) else {
                    continue;
                };
                if rewritten.is_none() && after.starts_with([' ', '.']) {
                    rewritten = Some(format!("{keyword}{to}{after}"));
                }
            }
        }
        out.push_str(rewritten.as_deref().unwrap_or(line));
    }
    out
}

/// `--missing` for a Python file: `existing`, the user's interface or
/// implementation of `fresh`'s component, with the methods of `fresh` it
/// lacks appended to its class; `None` when it lacks none. A method is
/// present when the class has a method taking its message first; one
/// taking an input as `cmd` where the proto declares a fact, or the
/// reverse, is refused.
pub(crate) fn complete(
    fresh: &ScaffoldFile,
    existing: &str,
) -> Result<Option<String>, CodegenError> {
    let not_found = || CodegenError::ScaffoldImplNotFound {
        path: fresh.path.clone(),
        component: fresh.component.clone(),
    };
    let Some(fresh_class) = class(&fresh.source, None) else {
        return Ok(None);
    };
    let user_class = class(existing, Some(&fresh_class.name)).ok_or_else(not_found)?;
    let package = fresh
        .component
        .rsplit_once('.')
        .map_or("", |(package, _)| package);
    let mut missing = Vec::new();
    for method in &fresh_class.methods {
        match user_class.methods.iter().find(|m| m.ty == method.ty) {
            Some(found)
                if is_input(&found.param)
                    && is_input(&method.param)
                    && found.param != method.param =>
            {
                return Err(CodegenError::InputMismatch {
                    path: fresh.path.clone(),
                    message: format!("{package}.{}", method.ty),
                    expected: method.param.clone(),
                    found: found.param.clone(),
                });
            }
            Some(_) => {}
            None => missing.push(&fresh.source[method.span.0..method.span.1]),
        }
    }
    if missing.is_empty() {
        return Ok(None);
    }
    let end = user_class.end;
    let mut insert = String::new();
    for block in missing {
        insert.push('\n');
        insert.push_str(block);
    }
    let mut completed = existing.to_string();
    if !completed[..end].ends_with('\n') {
        insert.insert(0, '\n');
    }
    completed.insert_str(end, &insert);
    Ok(Some(completed))
}

fn is_input(param: &str) -> bool {
    param == "cmd" || param == "fact"
}

/// A class of a Python module: its name, its methods and where its body
/// ends (the byte after its last non-blank line).
struct Class {
    name: String,
    methods: Vec<PyMethod>,
    end: usize,
}

/// One method: the first parameter after `self`, its annotated type, and
/// its text (from its `def` to the end of its body, newline included).
struct PyMethod {
    param: String,
    ty: String,
    span: (usize, usize),
}

/// The first top-level class of `source` (named `name` when given).
fn class(source: &str, name: Option<&str>) -> Option<Class> {
    let mut offset = 0;
    let lines: Vec<(usize, &str)> = source
        .split_inclusive('\n')
        .map(|l| {
            let at = offset;
            offset += l.len();
            (at, l)
        })
        .collect();
    let start = lines.iter().position(|(_, l)| {
        l.strip_prefix("class ").is_some_and(|rest| {
            let found: String = rest
                .chars()
                .take_while(|c| c.is_alphanumeric() || *c == '_')
                .collect();
            name.is_none_or(|n| n == found)
        })
    })?;
    let class_name: String = lines[start]
        .1
        .trim_start_matches("class ")
        .chars()
        .take_while(|c| c.is_alphanumeric() || *c == '_')
        .collect();
    // The body: every line after the header that is blank or indented.
    let mut last = start;
    for (i, (_, line)) in lines.iter().enumerate().skip(start + 1) {
        if line.trim().is_empty() {
            continue;
        }
        if !line.starts_with(' ') && !line.starts_with('\t') {
            break;
        }
        last = i;
    }
    let end = lines[last].0 + lines[last].1.len();
    let mut methods = Vec::new();
    let defs: Vec<usize> = (start + 1..=last)
        .filter(|&i| {
            let line = lines[i].1;
            line.starts_with("    def ") || line.starts_with("    async def ")
        })
        .collect();
    for (k, &i) in defs.iter().enumerate() {
        let stop = defs.get(k + 1).map_or(last, |next| {
            let mut j = next - 1;
            while j > i && lines[j].1.trim().is_empty() {
                j -= 1;
            }
            j
        });
        let text: String = lines[i..=stop].iter().map(|(_, l)| *l).collect();
        let Some((param, ty)) = first_param(&text) else {
            continue;
        };
        methods.push(PyMethod {
            param,
            ty,
            span: (lines[i].0, lines[stop].0 + lines[stop].1.len()),
        });
    }
    Some(Class {
        name: class_name,
        methods,
        end,
    })
}

/// The first parameter after `self` of a `def` but the state or the
/// projection it folds into, as `(name, type)`, a leading `_` of the name
/// dropped.
fn first_param(def: &str) -> Option<(String, String)> {
    let open = def.find('(')?;
    let params = &def[open + 1..];
    let close = params.find(')')?;
    let mut parts = params[..close].split(',').map(str::trim);
    let first = parts.next()?;
    if first != "self" {
        return None;
    }
    let (name, ty) = parts
        .find(|p| {
            p.split_once(':').is_some_and(|(n, _)| {
                !matches!(n.trim().trim_start_matches('_'), "state" | "projection")
            })
        })?
        .split_once(':')?;
    let ty = ty.trim().rsplit('.').next()?.to_string();
    Some((name.trim().trim_start_matches('_').to_string(), ty))
}
