/// The angzarr Python package (angzarr-client-python) the scaffold depends
/// on, pinned by commit: every project this CLI scaffolds gets this one.
pub const CLIENT_PYTHON_REV: &str = "c62dc8f1fa828193b0e5083b28bcb37444f6c655";
/// Where [`CLIENT_PYTHON_REV`] is fetched from.
pub const CLIENT_PYTHON_GIT: &str = "https://github.com/angzarr-io/angzarr-client-python";

/// The proto packages angzarr-client-python ships generated, imported from
/// `angzarr_client.proto` and never generated into a project.
const FRAMEWORK_PACKAGES: &[&str] = &["io.angzarr.v1", "io.angzarr.status", "sererr.v1"];
/// Black's line width, which the generated Python is laid out to.
const WIDTH: usize = 88;
/// The header of every generated file.
const GENERATED: &str =
    "# @generated by angzarr-codegen. Do not edit: `angzarr scaffold python` rewrites it.\n";
/// The names `domain.py` gives the harness's types beyond the shared
/// [`model::RESERVED`]: a reaction's and a projection's context.
const PYTHON_RESERVED: &[&str] = &["PageContext"];

/// Where `buf generate` reads the domain's protos from.
#[derive(Clone, PartialEq, Eq, Debug)]
pub enum ProtoInput {
    /// A git repository at a revision, the protos under its `proto`, as
    /// angzarr-project lays them out.
    Git { url: String, rev: String },
    /// A directory, relative to the project root (where buf runs) or
    /// absolute.
    Directory(String),
}

/// One Python component's project.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct PythonApp {
    /// What the project serves: a domain (its aggregate's or process
    /// manager's, e.g. `player`), or a component's name in an application
    /// (`component_name`, else its kind's default: `policy-table-player`,
    /// `projector-wallet-table-ledger`). The package is `angzarr_<domain>`,
    /// the distribution and its script `angzarr-<domain>`.
    pub domain: String,
    pub protos: ProtoInput,
    /// The build version the component reports as its rules_version.
    pub rules_version: String,
}

impl PythonApp {
    fn package(&self) -> String {
        format!("angzarr_{}", self.domain.replace('-', "_"))
    }

    fn script(&self) -> String {
        format!("angzarr-{}", self.domain.replace('_', "-"))
    }
}

/// One component as the Python scaffold emits it.
struct Unit {
    component: Component,
    /// Its name in an application: its `component_name`, else its kind's
    /// default.
    name: String,
    /// A policy's target's commands: what its reactions send.
    commands: Vec<MessageDescriptor>,
    /// A projector's source domains.
    sources: Vec<String>,
}

impl Unit {
    fn kind(&self) -> ComponentKind {
        self.component.kind
    }

    /// A domain: an aggregate or a process manager, deciding inputs and
    /// folding its events.
    fn is_domain(&self) -> bool {
        matches!(
            self.kind(),
            ComponentKind::Aggregate | ComponentKind::ProcessManager
        )
    }
}

/// The project of `app.domain`: the component of that domain, or of that
/// name, declared in `files`, as the files listed in the module doc. Paths
/// are relative to the project root.
pub fn scaffold_python(
    descriptor_set: &[u8],
    files: &[&str],
    app: &PythonApp,
) -> Result<Vec<ScaffoldFile>, CodegenError> {
    let components: Vec<Component> = model::components(descriptor_set, files, ALL_KINDS)?
        .into_iter()
        .filter(|c| c.domain == app.domain || c.component_name == app.domain)
        .collect();
    if components.is_empty() {
        return Err(CodegenError::PythonNoDomain {
            domain: app.domain.clone(),
        });
    }
    let units = components
        .into_iter()
        .map(|c| unit(c, descriptor_set))
        .collect::<Result<Vec<_>, _>>()?;
    for unit in &units {
        let (messages, enums) = reached(unit);
        let names: Vec<(&str, String)> = messages
            .iter()
            .map(|m| (m.full_name(), local_name(m.full_name(), m.package_name())))
            .chain(
                enums
                    .iter()
                    .map(|e| (e.full_name(), local_name(e.full_name(), e.package_name()))),
            )
            .collect();
        model::refuse_reserved(names.iter().cloned())?;
        if let Some((full, local)) = names
            .into_iter()
            .find(|(_, local)| PYTHON_RESERVED.contains(&local.as_str()))
        {
            return Err(CodegenError::ReservedName {
                message: full.to_string(),
                name: local,
            });
        }
    }
    let package = app.package();
    let src = format!("src/{package}");
    let anchor = units[0].component.anchor.full_name().to_string();
    let file = |path: String, source: String, owner: Owner| ScaffoldFile {
        component: anchor.clone(),
        path,
        source,
        owner,
    };
    let served = served(app, &units[0]);

    let mut out = vec![
        file(
            "pyproject.toml".to_string(),
            pyproject(app, &served, &units),
            Owner::User,
        ),
        file(
            "buf.gen.yaml".to_string(),
            buf_gen(app, &served, &units),
            Owner::Generated,
        ),
        file(format!("{src}/__init__.py"), String::new(), Owner::User),
        file(
            format!("{src}/__main__.py"),
            format!("{GENERATED}\nfrom {package}.main import main\n\nmain()\n"),
            Owner::Generated,
        ),
        file(
            format!("{src}/_version.py"),
            format!(
                "{GENERATED}\"\"\"The build version {served} reports as its rules_version.\"\"\"\n\n__version__ = {:?}\n",
                app.rules_version
            ),
            Owner::Generated,
        ),
        file(
            format!("{src}/main.py"),
            main_py(app, &served, &units),
            Owner::Generated,
        ),
        file(
            format!("{src}/_descriptor.py"),
            descriptor_py(app, &served, descriptor_set, files, &units[0])?,
            Owner::Generated,
        ),
        file("tests/__init__.py".to_string(), String::new(), Owner::User),
    ];
    let mut packages = BTreeSet::new();
    for unit in &units {
        let component = &unit.component;
        let dir = module_dir(&component.anchor);
        let mut path = String::new();
        for part in std::iter::once("_gen").chain(dir.split('/')) {
            if !path.is_empty() {
                path.push('/');
            }
            path.push_str(part);
            packages.insert(path.clone());
        }
        let stem = snake(&component.name);
        let own = |path: String, source: String, owner: Owner| ScaffoldFile {
            component: component.anchor.full_name().to_string(),
            path,
            source,
            owner,
        };
        out.push(own(
            format!("{src}/logic.py"),
            interface(app, unit),
            Owner::User,
        ));
        out.push(own(
            format!("{src}/logic_impl.py"),
            implementation(app, unit),
            Owner::User,
        ));
        out.push(own(
            format!("{src}/domain.py"),
            domain_py(&served, unit),
            Owner::Generated,
        ));
        out.push(own(
            format!("{src}/_gen/{dir}/{stem}_angzarr.py"),
            dispatch(app, unit),
            Owner::Generated,
        ));
    }
    for dir in packages {
        out.push(file(
            format!("{src}/{dir}/__init__.py"),
            GENERATED.to_string(),
            Owner::Generated,
        ));
    }
    out.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(crate::headed_files(out))
}

/// `component` with what its kind needs beside it: a policy's target's
/// commands (refused when no aggregate or process manager of the set owns
/// its `output_domain`), a projector's sources.
fn unit(component: Component, descriptor_set: &[u8]) -> Result<Unit, CodegenError> {
    let mut commands = Vec::new();
    if component.kind == ComponentKind::Policy {
        let pool = model::pool_components(descriptor_set)?;
        let target = pool
            .iter()
            .find(|t| t.kind != ComponentKind::Policy && t.domain == component.output_domain)
            .ok_or_else(|| CodegenError::UnownedDomain {
                policy: component.anchor.full_name().to_string(),
                domain: component.output_domain.clone(),
            })?;
        commands = target
            .inputs
            .iter()
            .filter(|i| !i.fact)
            .map(|i| i.message.clone())
            .collect();
    }
    let sources = if component.kind == ComponentKind::Projector {
        component.sources.clone()
    } else {
        Vec::new()
    };
    Ok(Unit {
        name: component.component_name.clone(),
        component,
        commands,
        sources,
    })
}

/// What the project serves, for its docs: `the player domain`, `the
/// policy-table-player policy`.
fn served(app: &PythonApp, unit: &Unit) -> String {
    match unit.kind() {
        ComponentKind::Aggregate | ComponentKind::ProcessManager => {
            format!("the {} domain", app.domain)
        }
        ComponentKind::Policy => format!("the {} policy", unit.name),
        ComponentKind::Projector => format!("the {} projector", unit.name),
    }
}

/// `served` with its first letter upper-cased.
fn capital(served: &str) -> String {
    let mut chars = served.chars();
    chars
        .next()
        .map(|c| c.to_ascii_uppercase().to_string() + chars.as_str())
        .unwrap_or_default()
}

/// `io/angzarr/examples/v1` for a message of `io/angzarr/examples/v1/x.proto`.
fn module_dir(message: &MessageDescriptor) -> String {
    let name = message.parent_file().name().to_string();
    name.rsplit_once('/')
        .map_or(String::new(), |(dir, _)| dir.to_string())
}

/// The dotted module of a message's pb2, under the project's `_gen`.
fn pb2_module(app: &PythonApp, message: &MessageDescriptor) -> String {
    let name = message.parent_file().name().to_string();
    let stem = name.trim_end_matches(".proto").replace('/', ".");
    format!("{}._gen.{stem}_pb2", app.package())
}

/// The pb2 alias the dispatch imports a message's module as: `_<stem>`.
fn alias(message: &MessageDescriptor) -> String {
    let name = message.parent_file().name().to_string();
    let stem = name
        .rsplit('/')
        .next()
        .unwrap_or(&name)
        .trim_end_matches(".proto");
    format!("_{stem}")
}

/// The messages the plain types start from: a domain's state, inputs,
/// what they emit and refuse, and its events; a policy's events and its
/// target's commands; a projector's projection and its events.
fn roots(unit: &Unit) -> Vec<MessageDescriptor> {
    let component = &unit.component;
    let mut roots = Vec::new();
    if component.kind != ComponentKind::Policy {
        roots.push(component.anchor.clone());
    }
    for input in &component.inputs {
        roots.push(input.message.clone());
        roots.extend(input.emits.iter().cloned());
        roots.extend(input.refuses.iter().cloned());
    }
    roots.extend(component.events.iter().cloned());
    roots.extend(unit.commands.iter().cloned());
    roots
}

/// A field's kind, a map's by its value.
fn element_kind(field: &prost_reflect::FieldDescriptor) -> Kind {
    match field.kind() {
        Kind::Message(entry) if entry.is_map_entry() => entry.map_entry_value_field().kind(),
        kind => kind,
    }
}

/// Every message and enum of the unit's plain types, every one its
/// [`roots`] reach, in the order they are reached, each once by its full
/// name (a policy's target commands are read from a pool of their own);
/// angzarr's own and google's excepted.
fn reached(unit: &Unit) -> (Vec<MessageDescriptor>, Vec<EnumDescriptor>) {
    let mut messages: Vec<MessageDescriptor> = Vec::new();
    let mut enums: Vec<EnumDescriptor> = Vec::new();
    let foreign =
        |package: &str| FRAMEWORK_PACKAGES.contains(&package) || package.starts_with("google.");
    let mut queue = roots(unit);
    let mut i = 0;
    while i < queue.len() {
        let message = queue[i].clone();
        i += 1;
        if messages
            .iter()
            .any(|m| m.full_name() == message.full_name())
            || foreign(message.package_name())
        {
            continue;
        }
        for field in message.fields() {
            match element_kind(&field) {
                Kind::Message(m) => queue.push(m),
                Kind::Enum(e)
                    if !foreign(e.package_name())
                        && !enums.iter().any(|known| known.full_name() == e.full_name()) =>
                {
                    enums.push(e)
                }
                _ => {}
            }
        }
        messages.push(message);
    }
    (messages, enums)
}

/// A Python name for a proto name: itself, `_` appended where it is a
/// keyword.
fn py_name(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class",
        "continue", "def", "del", "elif", "else", "except", "finally", "for", "from", "global",
        "if", "import", "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return",
        "try", "while", "with", "yield",
    ];
    if KEYWORDS.contains(&name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

/// `MOVE_ACTION_HIT` of `MoveAction` as `HIT`.
fn member(e: &EnumDescriptor, value: &str) -> String {
    py_name(wire_name(e, value))
}
