//! The Python scaffold: one component's uv project, served to
//! angzarr-embedded as a child process through angzarr-client-python's
//! harness (`angzarr_client.child`). The component is an aggregate or a
//! process manager of a domain, a policy, or a projector over one or
//! more source domains (decision 14.50).
//!
//! The project is split so that the user's logic never names the harness:
//!
//! - written once, the user's ([`Owner::User`]): `pyproject.toml`, the
//!   package's `__init__.py`, `tests/__init__.py`, the logic interface
//!   (`logic.py`, a `typing.Protocol` over the plain types: an aggregate's
//!   or a process manager's decision per command or fact and fold per
//!   event, a policy's reaction per event, a projector's coroutine per
//!   event) and its implementation (`logic_impl.py`, every method `raise
//!   NotImplementedError  # TODO`);
//! - rewritten on every run, the CLI's ([`Owner::Generated`]): `domain.py`
//!   (the messages as frozen dataclasses and enums, no protobuf),
//!   `buf.gen.yaml` (the wire types), `main.py`, `__main__.py`,
//!   `_version.py`, the `_gen` packages' `__init__.py`, and the dispatch,
//!   which converts the router binding's wire calls to calls on the logic.
//!
//! Every generated file stands on angzarr-client-python's public API only
//! (`angzarr_client.router`'s dispatch tables, `ComponentHost.add_<kind>`,
//! `run_child`), so a hand-written file can take its place. A change to the
//! harness or to the scaffold touches only generated files.
//!
//! One module per artefact: [`domain`] (`domain.py`), [`convert`] (the
//! wire converters), [`dispatch`], [`logic`] (the interface and its
//! implementation), [`project`] (`main.py`, `pyproject.toml`, `buf.gen.yaml`,
//! `_descriptor.py`), [`complete`] (`--missing`), and [`layout`], black's
//! line layout they share.

