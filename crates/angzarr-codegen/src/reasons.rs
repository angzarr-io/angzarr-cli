//! The framework's reason keys as constants, rendered from angzarr-project's
//! `catalog/reasons.toml` (decisions 14.37 and 14.42), for Rust and for
//! Python: one constant per key of its `[keys]`, documented with who answers
//! it, its status and its args. The catalog's `[retired]` keys are never
//! rendered: a retired key is never answered again, nor reused.
//!
//! The constants are for the components that answer the keys, the routers
//! and the coordinators, not for an application: `angzarr reasons` renders
//! them into the code that holds them.

use std::collections::BTreeMap;

use serde::Deserialize;

use crate::error::CodegenError;

/// The header of every rendered file.
const SOURCE: &str =
    "@generated by angzarr-codegen from angzarr-project's catalog/reasons.toml. Do not edit.";

#[derive(Deserialize)]
struct Catalog {
    keys: BTreeMap<String, Key>,
}

#[derive(Deserialize)]
struct Key {
    owner: String,
    status: String,
    args: Vec<String>,
}

impl Key {
    /// Who answers it, with what, and its args, each quoted with `quote`.
    fn doc(&self, quote: &str) -> String {
        let status = match self.status.as_str() {
            "READINESS" => "as a readiness refusal".to_string(),
            status => format!("with status {status}"),
        };
        let args = if self.args.is_empty() {
            "no args".to_string()
        } else {
            let args: Vec<String> = self
                .args
                .iter()
                .map(|a| format!("{quote}{a}{quote}"))
                .collect();
            format!("args: {}", args.join(", "))
        };
        format!("Answered by the {}, {status}; {args}.", self.owner)
    }
}

fn parse(catalog: &str) -> Result<Catalog, CodegenError> {
    toml::from_str(catalog).map_err(|e| CodegenError::Catalog {
        detail: e.to_string(),
    })
}

/// The catalog's keys, in order.
pub fn reason_keys(catalog: &str) -> Result<Vec<String>, CodegenError> {
    Ok(parse(catalog)?.keys.into_keys().collect())
}

/// The catalog's keys as Rust constants: `pub const KEY: &str = "KEY";`.
pub fn reasons_rust(catalog: &str) -> Result<String, CodegenError> {
    let mut out = format!("// {SOURCE}\n");
    for (name, key) in parse(catalog)?.keys {
        out.push_str(&format!(
            "\n/// {}\npub const {name}: &str = \"{name}\";\n",
            key.doc("`")
        ));
    }
    Ok(out)
}

/// The catalog's keys as Python constants: `KEY = "KEY"`, each with its
/// docstring.
pub fn reasons_python(catalog: &str) -> Result<String, CodegenError> {
    let mut out = format!("# {SOURCE}\n\"\"\"The framework's reason keys.\"\"\"\n");
    for (name, key) in parse(catalog)?.keys {
        out.push_str(&format!(
            "\n{name} = \"{name}\"\n\"\"\"{}\"\"\"\n",
            key.doc("``")
        ));
    }
    Ok(out)
}
