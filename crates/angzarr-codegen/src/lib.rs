/// The one comment line every file the generator writes opens with, in
/// the file's own comment syntax: angzarr-cli's LICENSE-EXCEPTION (owner
/// ruling 2026-10-31) leaves what it generates the user's to license.
pub const LICENCE_HEADER: &str = "Generated by angzarr-cli; you may license this file as you choose \
                                  (see angzarr-cli's LICENSE-EXCEPTION).";

/// `source` opening with [`LICENCE_HEADER`] as a comment in `path`'s
/// syntax (`//` for Rust, `#` for Python, TOML and YAML), once: a source
/// that already opens with it, a user's file read back, is returned as it
/// is, as is one of another kind.
pub(crate) fn headed(path: &str, source: String) -> String {
    let marker = if path.ends_with(".rs") {
        "//"
    } else if [".py", ".toml", ".yaml", ".yml"]
        .iter()
        .any(|ext| path.ends_with(ext))
    {
        "#"
    } else {
        return source;
    };
    let line = format!("{marker} {LICENCE_HEADER}\n");
    if source.starts_with(&line) {
        return source;
    }
    line + &source
}

/// Every file of `files`, [`headed`].
pub(crate) fn headed_files(files: Vec<ScaffoldFile>) -> Vec<ScaffoldFile> {
    files
        .into_iter()
        .map(|f| ScaffoldFile {
            source: headed(&f.path, f.source),
            ..f
        })
        .collect()
}

