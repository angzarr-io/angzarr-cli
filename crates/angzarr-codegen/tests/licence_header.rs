//! Every file the generator writes into a user's project, or into a build's
//! `OUT_DIR`, opens with one comment line naming angzarr-cli's
//! LICENSE-EXCEPTION, in the file's own comment syntax (owner ruling
//! 2026-10-31).

mod common;

use angzarr_codegen::{
    AppSeed, LICENCE_HEADER, ProtoInput, PythonApp, RetrySeed, ScaffoldFile, adapters, app,
    descriptors_rs, markup_domain, register, register_only, scaffold, scaffold_python,
};
use common::*;

const HEADER: &str = "Generated by angzarr-cli; you may license this file as you choose \
                      (see angzarr-cli's LICENSE-EXCEPTION).";

fn first_line(source: &str) -> &str {
    source.lines().next().unwrap_or("")
}

fn assert_headed(files: &[ScaffoldFile]) {
    assert!(!files.is_empty());
    for f in files {
        let marker = if f.path.ends_with(".rs") { "//" } else { "#" };
        assert_eq!(
            first_line(&f.source),
            format!("{marker} {HEADER}"),
            "{}",
            f.path
        );
    }
}

#[test]
fn the_header_is_the_rulings_line() {
    assert_eq!(LICENCE_HEADER, HEADER);
}

#[test]
fn every_rust_scaffold_file_is_headed() {
    assert_headed(&scaffold(&descriptors(BUYIN), BUYIN, &[]).unwrap());
}

#[test]
fn every_python_scaffold_file_is_headed() {
    let app = PythonApp {
        domain: "player".to_string(),
        protos: ProtoInput::Git {
            url: "https://github.com/angzarr-io/angzarr-project".to_string(),
            rev: "ef975bcf6fd6a0207476667d18ddc7bb29a10ab4".to_string(),
        },
        rules_version: "0.1.0".to_string(),
    };
    assert_headed(&scaffold_python(&descriptors(BLACKJACK), &[PLAYER], &app, &[]).unwrap());
}

#[test]
fn every_app_file_is_headed() {
    let seed = AppSeed {
        name: "shop".to_string(),
        includes: vec!["proto".to_string()],
        python: Vec::new(),
        expose: Vec::new(),
        retry: RetrySeed::default(),
        in_memory: false,
        angzarr_build: None,
        domain: None,
    };
    let shop = &["shop/v1/shop.proto"];
    assert_headed(&app(&descriptors(shop), shop, &seed, None, None).unwrap());
}

#[test]
fn a_users_existing_file_is_headed_once() {
    let seed = AppSeed {
        name: "shop".to_string(),
        includes: vec!["proto".to_string()],
        python: Vec::new(),
        expose: Vec::new(),
        retry: RetrySeed::default(),
        in_memory: false,
        angzarr_build: None,
        domain: None,
    };
    let shop = &["shop/v1/shop.proto"];
    let set = descriptors(shop);
    let first = app(&set, shop, &seed, None, None).unwrap();
    let config = first.iter().find(|f| f.path == "angzarr.toml").unwrap();
    let manifest = first.iter().find(|f| f.path == "Cargo.toml").unwrap();
    let again = app(
        &set,
        shop,
        &seed,
        Some(&config.source),
        Some(&manifest.source),
    )
    .unwrap();
    for f in &again {
        assert_eq!(f.source.matches(HEADER).count(), 1, "{}", f.path);
    }
}

#[test]
fn every_build_output_is_headed() {
    let set = descriptors(BUYIN);
    let line = format!("// {HEADER}");
    for source in [
        adapters(&set, BUYIN, &[], &|_| None).unwrap(),
        register(&set, BUYIN, &[]).unwrap(),
        register_only(&set, BUYIN, &[]).unwrap(),
        descriptors_rs(&set, BUYIN, &[], "1.0.0").unwrap(),
    ] {
        assert_eq!(first_line(&source), line);
    }
    for generated in markup_domain(&set, BUYIN, BUYIN_WIRE).unwrap() {
        assert_eq!(first_line(&generated.source), line, "{}", generated.package);
    }
}
